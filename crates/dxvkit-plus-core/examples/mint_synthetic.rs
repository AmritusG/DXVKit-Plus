//! Mint the two synthetic HAP fixtures no encoder we may use can write (CC0, our own bytes):
//!
//! - `synthetic_hap7.mov`: HAP R (BC7), 64x32, 3 frames of random blocks — every BC7 mode, 16
//!   blocks per mode per frame, a different seed per frame;
//! - `synthetic_haph.mov`: HAP HDR (BC6H unsigned, mode 11 solid blocks), 16x16, 3 frames, one
//!   level per frame.
//!
//! ```text
//! cargo run -p dxvkit-plus-core --example mint_synthetic -- tests/fixtures
//! ```
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic, clippy::indexing_slicing, clippy::arithmetic_side_effects)]

#[path = "../../../tests/support/qt_movie.rs"]
mod qt_movie;

use sha2::{Digest, Sha256};
use std::path::Path;

fn splitmix(state: &mut u64) -> u64 {
    *state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let mut z = *state;
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

fn write(dir: &Path, name: &str, title: &str, bytes: &[u8], notes: &str) {
    std::fs::write(dir.join(name), bytes).unwrap();
    let sha: String = Sha256::digest(bytes).iter().map(|b| format!("{b:02x}")).collect();
    let sidecar = format!(
        "asset: tests/fixtures/{name}\ntitle: {title}\nauthor: Amrit Rosell — synthetic blocks written by crates/dxvkit-plus-core/examples/mint_synthetic.rs\nsource: Generated by crates/dxvkit-plus-core/examples/mint_synthetic.rs (deterministic; no encoder)\nlicense: CC0-1.0\nadded: 2026-10-11\nsha256: {sha}\nnotes: {notes}\n"
    );
    std::fs::write(dir.join(format!("{name}.attribution")), sidecar).unwrap();
    println!("{name}: {} bytes", bytes.len());
}

fn main() {
    let dir = std::env::args().nth(1).expect("output dir");
    let dir = Path::new(&dir);
    let frames: Vec<Vec<u8>> = (0..3u64)
        .map(|f| {
            let mut state = 0xB7_0000 + f;
            let mut blocks = Vec::new();
            for mode in 0..8u32 {
                for _ in 0..16 {
                    let mut v = (u128::from(splitmix(&mut state)) << 64) | u128::from(splitmix(&mut state));
                    v &= !((1u128 << (mode + 1)) - 1);
                    v |= 1u128 << mode;
                    blocks.extend_from_slice(&v.to_le_bytes());
                }
            }
            qt_movie::hap_frame(0xAC, &blocks)
        })
        .collect();
    write(
        dir,
        "synthetic_hap7.mov",
        "HAP R (Hap7, BC7) 64x32, random blocks of all 8 modes",
        &qt_movie::video_movie(b"Hap7", 64, 32, &frames),
        "No encoder we may use writes HAP R; these random BC7 blocks (row k = mode k) exercise every BC7 mode. The CPU decode equals the GPU's bit for bit.",
    );
    let frames: Vec<Vec<u8>> = [(462u128, 0u128, 462u128), (0, 462, 0), (300, 300, 300)]
        .iter()
        .map(|&(r, g, b)| qt_movie::hap_frame(0xA2, &(0..16).flat_map(|_| qt_movie::bc6h_solid(r, g, b)).collect::<Vec<u8>>()))
        .collect();
    write(
        dir,
        "synthetic_haph.mov",
        "HAP HDR (HapH, BC6H unsigned) 16x16, solid blocks",
        &qt_movie::video_movie(b"HapH", 16, 16, &frames),
        "No encoder we may use writes HAP HDR; BC6H mode-11 solid blocks built from the public BPTC definition (frame 0 magenta 0.5, frame 1 green 0.5, frame 2 grey).",
    );
}
